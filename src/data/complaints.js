const writeData = (data) => {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
};

export const seedMockData = () => {
  if (!readData()) {
    writeData(mockComplaints);
  }
};

export const getComplaints = () => {
  seedMockData();
  return readData() || [];
};

export const updateComplaint = (id, patch) => {
  const data = getComplaints();
  const updated = data.map((item) =>
    item.id === id ? { ...item, ...patch } : item
  );
  writeData(updated);
  return updated;
};

export const addComplaint = (data) => {
  const current = getComplaints();
  const newItem = {
    id: `cmp-${String(current.length + 1).padStart(3, "0")}`,
    customer_name: data.customer_name || "Anonim",
    contactNumber: data.contactNumber || null,
    sentiment: data.sentiment || "neutral",
    category: data.category || "digər",
    summary: data.summary || "",
    complaint: data.complaint || "",
    department: data.department || "Əməliyyat",
    priority: data.priority || 3,
    branchName: data.branchName || "",
    severity_code: data.severity_code || "Code Green",
    source: data.source || "whatsapp",
    status: data.status || "new",
    createdAt: data.createdAt || new Date().toISOString()
  };
  const updated = [newItem, ...current];
  writeData(updated);
  return updated;
};
